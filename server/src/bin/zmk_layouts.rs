use std::fs;
use anyhow::{Result, Context};
use tree_sitter::{Parser, Node};

#[cfg(feature = "runfiles")]
use runfiles::Runfiles;

#[derive(Debug, Clone)]
struct PhysicalKey {
    pub width: i32,
    pub height: i32,
    pub x: i32,
    pub y: i32,
    pub rotation: i32,
}

#[derive(Debug, Clone)]
struct Layout {
    pub name: String,
    pub display_name: Option<String>,
    pub keys: Vec<PhysicalKey>,
    pub source_file: String,
}

fn main() -> Result<()> {
    let args: Vec<String> = std::env::args().collect();
    
    let (zmk_path_buf, output_path) = if args.len() >= 2 {
        let zmk = std::path::PathBuf::from(&args[1]);
        let out = if args.len() >= 3 {
            Some(std::path::PathBuf::from(&args[2]))
        } else {
            None
        };
        (zmk, out)
    } else {
        #[cfg(feature = "runfiles")]
        {
            let r = Runfiles::create()?;
            let dtsi_path = runfiles::rlocation!(r, "zmk/app/dts/behaviors.dtsi");
            
            if let Some(dtsi_path) = dtsi_path {
                let zmk = dtsi_path.parent()
                    .and_then(|p| p.parent())
                    .and_then(|p| p.parent())
                    .map(|p| p.to_path_buf())
                    .context("Could not find zmk root from behaviors.dtsi path")?;
                
                let out = if let Some(ws_root) = std::env::var_os("BUILD_WORKSPACE_DIRECTORY") {
                    let mut p = std::path::PathBuf::from(ws_root);
                    p.push("src/keymap/layouts.rs");
                    Some(p)
                } else {
                    Some(std::path::PathBuf::from("src/keymap/layouts.rs"))
                };
                (zmk, out)
            } else {
                eprintln!("Usage: {} <zmk_path> [output_path]", args[0]);
                std::process::exit(1);
            }
        }
        #[cfg(not(feature = "runfiles"))]
        {
            eprintln!("Usage: {} <zmk_path> [output_path]", args[0]);
            std::process::exit(1);
        }
    };

    let zmk_path = zmk_path_buf.as_path();
    let mut layouts = Vec::new();
    let mut parser = Parser::new();
    parser.set_language(&tree_sitter_devicetree::LANGUAGE.into())?;

    let boards_dir = zmk_path.join("app/boards");
    
    // Find all *-layouts.dtsi files
    fn find_layout_files(dir: &std::path::Path, files: &mut Vec<std::path::PathBuf>) -> Result<()> {
        if dir.is_dir() {
            for entry in fs::read_dir(dir)? {
                let entry = entry?;
                let path = entry.path();
                if path.is_dir() {
                    find_layout_files(&path, files)?;
                } else if path.file_name().and_then(|n| n.to_str()).map_or(false, |n| n.ends_with("-layouts.dtsi")) {
                    files.push(path);
                }
            }
        }
        Ok(())
    }

    let mut layout_files = Vec::new();
    find_layout_files(&boards_dir, &mut layout_files)?;

    for path in layout_files {
        let content = fs::read_to_string(&path)?;
        let tree = parser.parse(&content, None).context("Failed to parse DTS")?;
        let filename = path.strip_prefix(zmk_path).unwrap_or(&path).to_string_lossy().to_string();
        
        extract_layouts(tree.root_node(), &content, &filename, &mut layouts)?;
    }

    // 3. Generate Rust code
    let mut output = String::new();
    output.push_str("// Generated by server/src/bin/zmk_layouts.rs. DO NOT EDIT.\n");
    output.push_str("// To regenerate, run:\n");
    output.push_str("// bazel run //server:zmk_layouts\n\n");
    output.push_str("use super::PhysicalKey;\n\n");
    output.push_str("pub struct ZmkLayout {\n");
    output.push_str("    pub name: &'static str,\n");
    output.push_str("    pub display_name: Option<&'static str>,\n");
    output.push_str("    pub keys: &'static [PhysicalKey],\n");
    output.push_str("    pub source_file: &'static str,\n");
    output.push_str("}\n\n");
    output.push_str("pub const ZMK_LAYOUTS: &[ZmkLayout] = &[\n");
    
    for l in &layouts {
        output.push_str("    ZmkLayout {\n");
        output.push_str(&format!("        name: \"{}\",\n", l.name));
        if let Some(dn) = &l.display_name {
            output.push_str(&format!("        display_name: Some(\"{}\"),\n", dn));
        } else {
            output.push_str("        display_name: None,\n");
        }
        output.push_str("        keys: &[\n");
        for k in &l.keys {
            output.push_str(&format!("            PhysicalKey {{ width: {}, height: {}, x: {}, y: {}, rotation: {} }},\n", k.width, k.height, k.x, k.y, k.rotation));
        }
        output.push_str("        ],\n");
        output.push_str(&format!("        source_file: \"{}\",\n", l.source_file));
        output.push_str("    },\n");
    }
    output.push_str("];\n");

    if let Some(out_path) = output_path {
        fs::write(out_path, output)?;
    } else {
        println!("{}", output);
    }

    Ok(())
}

fn extract_layouts(
    node: Node, 
    source: &str, 
    filename: &str, 
    layouts: &mut Vec<Layout>
) -> Result<()> {
    if node.kind() == "node" {
        let mut is_layout = false;
        let mut display_name = None;
        let mut keys = Vec::new();
        
        let mut cursor = node.walk();
        for child in node.children(&mut cursor) {
            if child.kind() == "property" {
                let prop_name = child.child_by_field_name("name")
                    .map(|n| n.utf8_text(source.as_bytes()).unwrap_or(""))
                    .unwrap_or("");
                
                if prop_name == "compatible" {
                    let val = child.child_by_field_name("value")
                        .map(|n| n.utf8_text(source.as_bytes()).unwrap_or(""))
                        .unwrap_or("");
                    if val.contains("zmk,physical-layout") {
                        is_layout = true;
                    }
                } else if prop_name == "display-name" {
                    let val = child.child_by_field_name("value")
                        .map(|n| n.utf8_text(source.as_bytes()).unwrap_or(""))
                        .unwrap_or("");
                    display_name = Some(val.trim_matches('\"').to_string());
                } else if prop_name == "keys" {
                    let mut cursor = child.walk();
                    for val_node in child.children(&mut cursor) {
                        if val_node.kind() != "identifier" {
                            let raw_val = val_node.utf8_text(source.as_bytes()).unwrap_or("");
                            let num_re = r"\(?([\d-]+)\)?";
                            // Format: width, height, x, y, rotation, col_offset, row_offset
                            let key_re_str = format!(r"&key_physical_attrs\s+{}\s+{}\s+{}\s+{}\s+{}\s+{}\s+{}", num_re, num_re, num_re, num_re, num_re, num_re, num_re);
                            let key_regex = regex::Regex::new(&key_re_str).unwrap();
                            for cap in key_regex.captures_iter(raw_val) {
                                keys.push(PhysicalKey {
                                    width: cap[1].parse().unwrap_or(100),
                                    height: cap[2].parse().unwrap_or(100),
                                    x: cap[3].parse().unwrap_or(0),
                                    y: cap[4].parse().unwrap_or(0),
                                    rotation: cap[5].parse().unwrap_or(0),
                                });
                            }
                        }
                    }
                }
            }
        }
        
        if is_layout && !keys.is_empty() {
            let node_name = node.child_by_field_name("name")
                .map(|n| n.utf8_text(source.as_bytes()).unwrap_or(""))
                .unwrap_or("")
                .to_string();
            
            layouts.push(Layout {
                name: node_name,
                display_name,
                keys,
                source_file: filename.to_string(),
            });
        }
    }

    let mut cursor = node.walk();
    for child in node.children(&mut cursor) {
        extract_layouts(child, source, filename, layouts)?;
    }
    
    Ok(())
}
