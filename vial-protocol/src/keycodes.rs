/// Extract layer function type and layer number from a keycode, if applicable.
pub fn layer_info(keycode: u16, protocol_version: u32) -> Option<(&'static str, u8)> {
    let hi = keycode & 0xFF00;
    let layer = (keycode & 0x1F) as u8;
    
    if protocol_version >= 6 {
        // v6 mappings
        match keycode {
            0x5200..=0x521F => Some(("TO", layer)),
            0x5220..=0x523F => Some(("MO", layer)),
            0x5240..=0x525F => Some(("DF", layer)),
            0x5260..=0x527F => Some(("TG", layer)),
            0x5280..=0x529F => Some(("OSL", layer)),
            0x52C0..=0x52DF => Some(("TT", layer)),
            0x52E0..=0x52FF => Some(("PDF", layer)),
            0x4000..=0x4FFF => {
                let lt_layer = ((keycode >> 8) & 0x0F) as u8;
                Some(("LT", lt_layer))
            }
            _ => None,
        }
    } else {
        // v5 mappings
        match hi {
            0x5000 => Some(("TO", layer)),
            0x5100 => Some(("MO", layer)),
            0x5200 => Some(("DF", layer)),
            0x5300 => Some(("TG", layer)),
            0x5400 => Some(("OSL", layer)),
            0x5800 => Some(("TT", layer)),
            0x4000..=0x4F00 => { // LT in v5 is 0x4000
                let lt_layer = ((keycode >> 8) & 0x0F) as u8;
                Some(("LT", lt_layer))
            }
            _ => None,
        }
    }
}

/// Human-readable display information for a QMK keycode.
#[derive(Clone, Debug, PartialEq, Default)]
pub struct KeyDisplay {
    pub upper_left: String,
    pub upper_middle: String,
    pub upper_right: String,
    pub middle: String,
    pub lower_left: String,
    pub lower_right: String,
}

/// Get structured display info for a keycode.
pub fn keycode_display(keycode: u16, protocol_version: u32, keyboard_name: &str) -> KeyDisplay {
    let mut disp = KeyDisplay::default();

    if keycode == 0x0000 {
        return disp;
    }
    if keycode == 0x0001 {
        disp.middle = "▽".into();
        return disp;
    }

    // Layer functions
    if let Some((func, layer)) = layer_info(keycode, protocol_version) {
        disp.upper_left = func.into();
        disp.middle = format!("{}", layer);
        if func == "LT" {
            let tap_kc = (keycode & 0xFF) as u16;
            disp.upper_right = keycode_label(tap_kc, protocol_version, keyboard_name);
        }
        return disp;
    }

    // Mod-tap
    let is_mod_tap = if protocol_version >= 6 {
        keycode & 0xE000 == 0x2000
    } else {
        keycode & 0xE000 == 0x6000
    };

    if is_mod_tap {
        let mods = ((keycode >> 8) & 0x1F) as u8;
        let basic = (keycode & 0xFF) as u16;
        let mod_name = match mods {
            0x01 => "LCtl",
            0x02 => "LSft",
            0x04 => "LAlt",
            0x08 => "LGui",
            0x11 => "RCtl",
            0x12 => "RSft",
            0x14 => "RAlt",
            0x18 => "RGui",
            _ => "Mod",
        };
        disp.upper_left = "MT".into();
        disp.upper_right = keycode_label(basic, protocol_version, keyboard_name);
        disp.middle = mod_name.into();
        return disp;
    }

    // Basic key with modifiers applied
    if (keycode & 0xFF00 >= 0x0100) && (keycode & 0xFF00 <= 0x1F00) && (keycode & 0xFF != 0) {
        let mods = ((keycode >> 8) & 0x1F) as u8;
        let basic = (keycode & 0xFF) as u16;
        let mod_name = match mods {
            0x01 => "LCtl",
            0x02 => "LSft",
            0x04 => "LAlt",
            0x08 => "LGui",
            0x11 => "RCtrl",
            0x12 => "RShift",
            0x14 => "RAlt",
            0x18 => "RGui",
            _ => "Mod",
        };
        disp.upper_left = mod_name.into();
        disp.middle = keycode_label(basic, protocol_version, keyboard_name);
        return disp;
    }

    let label = keycode_label(keycode, protocol_version, keyboard_name);
    if label.contains(' ') && label.len() > 2 && !label.starts_with("Vol") && !label.starts_with("Media") && !label.starts_with("Next") && !label.starts_with("Prev") {
        let parts: Vec<&str> = label.splitn(2, ' ').collect();
        if parts.len() == 2 {
            disp.upper_middle = parts[1].into();
            disp.middle = parts[0].into();
            return disp;
        }
    }

    disp.middle = label;
    disp
}

