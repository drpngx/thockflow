// Dump keybard's keycode catalog (keygen.ts) numbered as QMK keycode version 0.0.9
// (constants/keycode-numbering.ts) into a Rust source file.
//
// Usage: node dump_keycodes.mjs <keygen.ts> <0.0.9.json> <out.rs>
import fs from "node:fs";

const [, , keygenPath, jsonPath, outPath] = process.argv;
let src = fs.readFileSync(keygenPath, "utf8");
src = src
  .replace(/^import .*$/m, "")
  .replace(/export const (\w+): \w+ =/g, "globalThis.$1 =");
eval(src);
const { CODEMAP, KEYMAP, KEYALIASES } = globalThis;
const spec = JSON.parse(fs.readFileSync(jsonPath, "utf8"));

// --- applyKeycodeNumbering(spec), copied from keybard ---
const RENAMED = {
  QK_STENO_BOLT: "QK_STENO_MODE_BOLT",
  QK_STENO_GEMINI: "QK_STENO_MODE_GEMINI",
  QK_STENO_COMB: "QK_STENO_S3",
  QK_STENO_COMB_MAX: "QK_STENO_EU",
};
const qmkNameFor = (name) =>
  name in RENAMED ? RENAMED[name] : name.startsWith("STN_") ? "QK_STENO_" + name.slice(4) : name;
const baseCodes = new Map(Object.entries(KEYMAP).map(([n, e]) => [n, e.code]));
const baseCodemap = { ...CODEMAP };
const catalogNamesFor = new Map();
for (const name of baseCodes.keys()) {
  const q = qmkNameFor(name);
  catalogNamesFor.set(q, [...(catalogNamesFor.get(q) ?? []), name]);
}
const namesByCode = new Map();
for (const [hex, qmkNames] of Object.entries(spec.keycodes)) {
  const code = parseInt(hex, 16);
  const names = [...new Set(qmkNames.flatMap((n) => [n, ...(catalogNamesFor.get(n) ?? [])]))].filter(
    (n) => n in KEYMAP,
  );
  if (!names.length) {
    const [key] = qmkNames;
    KEYMAP[key] = { code, qmkid: key };
    names.push(key);
  }
  for (const name of names) KEYMAP[name].code = code;
  for (const alias of qmkNames) {
    if (!(alias in KEYMAP) && !(alias in KEYALIASES)) KEYALIASES[alias] = names[0];
  }
  namesByCode.set(code, names);
}
const labels = new Set(Object.values(baseCodemap));
for (const [code, names] of namesByCode) {
  const current = baseCodemap[code];
  if (current && KEYMAP[current]?.code === code) continue;
  CODEMAP[code] = names.find((n) => labels.has(n)) ?? names[0];
}
for (const [code, name] of Object.entries(baseCodemap)) {
  const number = Number(code);
  if (!namesByCode.has(number) && KEYMAP[name] && KEYMAP[name].code !== number) delete CODEMAP[number];
}
// generateAllKeycodes: PDF(i) is an alias of DF(i)
for (let i = 0; i < 32; i++) KEYALIASES[`PDF(${i})`] ??= `DF(${i})`;

// --- emit ---
const esc = (s) => JSON.stringify(s);
const codeToName = Object.entries(CODEMAP)
  .map(([c, n]) => [Number(c), n])
  .sort((a, b) => a[0] - b[0]);
const nameToCode = new Map();
for (const [name, e] of Object.entries(KEYMAP)) nameToCode.set(name, e.code);
for (const [alias, target] of Object.entries(KEYALIASES)) {
  if (!nameToCode.has(alias) && KEYMAP[target]) nameToCode.set(alias, KEYMAP[target].code);
}
const names = [...nameToCode.entries()].sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));

let out = `// @generated by dump_keycodes.mjs from keybard's keycode catalog
// (src/constants/keygen.ts) numbered as QMK keycode version ${spec.version}.
// Do not edit by hand.

/// QMK keycode version these tables number keycodes in.
pub const KEYCODE_VERSION: &str = ${esc(spec.version)};

/// Code -> canonical name, sorted by code. Templates end in \`(kc)\`.
pub static CODE_TO_NAME: &[(u16, &str)] = &[
`;
for (const [c, n] of codeToName) out += `    (0x${c.toString(16).padStart(4, "0")}, ${esc(n)}),\n`;
out += `];

/// Name or alias -> code, sorted by name.
pub static NAME_TO_CODE: &[(&str, u16)] = &[
`;
for (const [n, c] of names) out += `    (${esc(n)}, 0x${c.toString(16).padStart(4, "0")}),\n`;
out += `];

/// QMK keycode ranges ("first/size" -> name).
pub static RANGES: &[(u16, u16, &str)] = &[
`;
for (const [span, name] of Object.entries(spec.ranges)) {
  const [first, size] = span.split("/").map((x) => parseInt(x, 16));
  out += `    (0x${first.toString(16).padStart(4, "0")}, 0x${size.toString(16).padStart(4, "0")}, ${esc(name)}),\n`;
}
out += `];
`;
fs.writeFileSync(outPath, out);
console.log(`codes: ${codeToName.length}, names: ${names.length}`);
